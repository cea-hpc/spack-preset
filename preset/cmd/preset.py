description = "developer build: generate a cmake json preset"
" https://cmake.org/cmake/help/latest/manual/cmake-presets.7.html"
section = "build"
level = "long"


@memoized
def _cmake_define_re():
    return re.compile(
        r"^(\-D)?(?P<variable>[^:=]+)(:(?P<type>(BOOL|PATH|FILEPATH|STRING|INTERNAL|STATIC|UNINITIALIZED)))?(=(?P<value>.+))?$"  # noqa: E501
    )


def parse_cmake_define(arg):
    """Parse `"-Dvar:type=val"` and return `(var, type, val)`.

    `(None, None, None)` is returned when arg is not recognized.

    type and val are optional and so can be None.
    """
    m = _cmake_define_re().match(arg)
    if not m:
        return None, None, None
    g = m.groupdict()
    return g["variable"], g.get("type", None), g.get("value", None)


def escape_cmake_macros(fmt):
    """Escapes cmake macros so they are not interpreted as spack spec format string"""
    return re.sub(
        r"((?<!\\)(?:\\\\)*\$[a-z0-9_-]*)\{([^{}]*)\}", r"\1\{\2\}", fmt, flags=re.IGNORECASE
    )


def spec_format_string(spec, fmt, user_spec=None, format_path=False):
    """Format a spec, with a couple additions"""
    fmt = escape_cmake_macros(fmt)
    # Hack spec to implement '{user_spec}' in format string
    if user_spec is not None:
        assert getattr(spec, "user_spec", user_spec) is user_spec
        spec.user_spec = user_spec
    # FIXME: spec.format_path converts '$\{HOME\}' to '__HOME_'
    # spec_format = spec.format_path if format_path else spec.format
    spec_format = spec.format
    return spec_format(fmt)


def setup_parser(subparser):
    """Argparse."""
    subparser.epilog = dedent(
        """
        FORMAT STRING argument values are resolved twice:
        - Spack spec format string elements are resolved now (e.g '{name}-{version}-{architecture.target}')
        - CMake macros elements are left as-is for later resolution (e.g. '$penv{HOME}')
            https://cmake.org/cmake/help/v3.24/manual/cmake-presets.7.html#macro-expansion
        """
    )
    fmtstrdoc = "See FORMAT STRING below."
    subparser.add_argument(
        "-o",
        "--output",
        default="CMakeUserPresets.json",
        help="output presets json file (default to current dir. ./CMakeUserPresets.json)",
    )
    subparser.add_argument("-y", "--overwrite", action="store_true", help="overwrite presets")
    subparser.add_argument(
        "--with-name", default="{hash}", type=str, help="Preset 'name'. " + fmtstrdoc
    )
    subparser.add_argument(
        "--with-display-name",
        default="{architecture.target}-{compiler.name}-{compiler.version}"
        " generated by spack preset {user_spec}",
        type=str,
        help="Preset 'displayName'. " + fmtstrdoc,
    )
    subparser.add_argument(
        "--with-description",
        default="Generated by spack preset {user_spec}: " + DISPLAY_FORMAT,
        type=str,
        help="Preset 'description'. " + fmtstrdoc,
    )
    subparser.add_argument(
        "--build-dir", default=None, type=str, help="Preset 'buildDir'. " + fmtstrdoc
    )
    subparser.add_argument(
        "--no-build",
        action="store_true",
        help="Don't generate build presets (only configuration presets)",
    )
    subparser.add_argument("--no-test", action="store_true", help="don't generate test presets")
    subparser.add_argument(
        "--hidden", action="store_true", help="mark configure presets as 'hidden'"
    )
    subparser.add_argument(
        "--cm-version", type=int, help="set schema <version> into json preset file"
    )
    subparser.add_argument(
        "-D",
        "--cmake-arg",
        type=str,
        dest="cmake_args",
        action="append",
        default=[],
        help="Set additional cmake variable in profile (can be used multiple times)",
    )
    subparser.add_argument(
        "-x",
        "--exclude",
        type=str,
        dest="exclude_specs",
        action="append",
        default=[],
        help="Exclude spec (can be used multiple times), WARNING quote if spec is multiworded",
    )
    subparser.add_argument(
        "--no-deps-install", action="store_true", help="do not install missing dependencies"
    )
    arguments.add_common_arguments(subparser, ["no_checksum"])
    cd_group = subparser.add_mutually_exclusive_group()
    arguments.add_common_arguments(cd_group, ["clean", "dirty"])

    arguments.add_common_arguments(subparser, ["constraint"])


def preset(parser, args):
    """Command."""

    output = pathlib.Path(args.output)

    if output.exists():
        try:
            with output.open("r") as json_file:
                presets = json.load(json_file)
        except json.decoder.JSONDecodeError as e:
            tty.die(args.output + ": " + str(e))
    else:
        presets = None

    user_cmake_args = []
    for arg in args.cmake_args:
        name_type_value = parse_cmake_define(arg)
        if name_type_value == (None, None, None):
            tty.die(f"{arg!r}: invalid cmake variable")
        user_cmake_args.append(name_type_value)

    if ev.active_environment():
        env = ev.active_environment()

        if args.constraint:  # filter requested spec from env
            user_specs = spack.cmd.parse_specs(args.constraint)
            specs = []
            for user_root, root in env.concretized_specs():
                for dep in root.traverse(deptype="all", root=True, cover="nodes"):
                    for user_spec in user_specs:
                        if dep.satisfies(user_spec):
                            specs.append((f"{user_spec} VIA ROOT SPEC {user_root}", dep))
            if not specs:
                tty.die(f"Could not find any specs in env matching '{args.constraint}'")

        else:  # get all user specs
            specs = list(env.concretized_specs())
            if not specs:
                tty.die("Could not find any specs in env")

    elif args.constraint:
        specs = []
        for user_spec in spack.cmd.parse_specs(args.constraint):
            spec = user_spec.copy()
            if not spec.concrete:
                tty.msg(f"Concretize {user_spec} ...")
                concretized_spec = spack.concretize.concretize_one(spec, True)
            specs.append((user_spec, concretized_spec))

    else:
        tty.die(
            "spack preset requires a package spec argument"
            " or specs from active environment."
        )

    # if needed exclude specs from list
    if args.exclude_specs:
        for spec_to_be_excluded in args.exclude_specs:
            filtered_specs = [spec for spec in specs if not spec[1].satisfies(spec_to_be_excluded)]
            specs = filtered_specs

    if presets is None:
        presets = {"version": args.cm_version if args.cm_version else 5}

    if "configurePresets" not in presets:
        presets["configurePresets"] = []

    if not args.no_build:  # that is build ;x
        # yes generate buildPresets keys
        if "buildPresets" not in presets:
            presets["buildPresets"] = []

    if not args.no_test:
        # yes generate testPresets keys
        if "testPresets" not in presets:
            presets["testPresets"] = []

    preset_names = []
    for user_spec, spec in specs:
        preset_name = spec_format_string(spec, args.with_name, user_spec=user_spec)
        other = next(iter(us for (us, s), n in zip(specs, preset_names) if n == preset_name), None)
        if other is not None:
            if preset_name == args.with_name:
                name = f"{preset_name!r}"
            else:
                name = f"{preset_name!r} (formatted from {args.with_name!r})"
            msg = (
                f"Found multiple specs getting the same cmake preset name {name}:"
                f"\n  - {other}"
                f"\n  - {user_spec}"
                "\n(Try to change --with-name or spec constraint to avoid conflict)"
            )
            tty.die(msg)

        preset_names.append(preset_name)

    for (user_spec, spec), preset_name in zip(specs, preset_names):
        print_tree_kwargs = {
            "cover": "nodes",
            "hashlen": 7,
            "deptypes": "all",
            "show_types": True,
            "status_fn": spack.spec.Spec.install_status,
        }
        tty.msg(f"Spec {user_spec}:")
        tty.msg(spec.tree(**print_tree_kwargs))
        missing = any(not d.installed for d in spec.dependencies(deptype="all"))
        if not args.no_deps_install and missing:
            tty.msg(f"Install missing dependencies for {user_spec} ...")

            # Note that in normal case, only dependencies must be
            # explicit in --only-dependencies (and not root package).
            explicit = [spec.dag_hash()]

            install_kwargs = {
                "fail_fast": True,
                "install_deps": True,
                "install_package": False,
                "explicit": explicit,
                "include_build_deps": True,
                "verbose": args.verbose,  # or args.install_verbose,
                # "fail_fast": args.fail_fast,
                # "keep_prefix": args.keep_prefix,
                # "keep_stage": args.keep_stage,
                # "restage": not args.dont_restage,
                # "install_source": args.install_source,
                # "verbose": args.verbose or args.install_verbose,
                # "fake": args.fake,
                # "dirty": args.dirty,
                # "package_use_cache": cache_opt(args.use_cache, pkg_use_bc),
                # "package_cache_only": cache_opt(args.cache_only, pkg_use_bc),
                # "dependencies_use_cache": cache_opt(args.use_cache, dep_use_bc),
                # "dependencies_cache_only": cache_opt(args.cache_only, dep_use_bc),
                # "include_build_deps": args.include_build_deps,
                # "explicit": True,  # Use true as a default for install command
                # "stop_at": args.until,
                # "unsigned": args.unsigned,
                # "install_deps": ("dependencies" in args.things_to_install),
                # "install_package": ("package" in args.things_to_install),
            }
            builder = PackageInstaller([spec.package], **install_kwargs)
            builder.install()

    orig_env = os.environ.copy()

    for (user_spec, spec), preset_name in zip(specs, preset_names):

        os.environ.clear()
        os.environ.update(orig_env)

        # preset already present?
        previous_preset_existed = False
        if any(p["name"] == preset_name for p in presets["configurePresets"]):
            if not args.overwrite:
                tty.die(
                    f"Preset {preset_name!r} already present in {args.output!r}. "
                    + "Please use `-y' to overwrite"
                )
            else:  # purge old presets before "re-"appending
                for preset_type in ["configurePresets", "buildPresets", "testPresets"]:
                    if preset_type in presets:
                        for i in reversed(range(len(presets[preset_type]))):
                            if presets[preset_type][i].get("name") == preset_name:
                                previous_preset_existed = True
                                del presets[preset_type][i]

        if previous_preset_existed:
            tty.msg(f"Replacing existing preset {preset_name!r} for {user_spec} ...")
        else:
            tty.msg(f"Adding new preset {preset_name!r} for {user_spec} ...")

        source_path = output.parent

        fake_link_to_build_stage = source_path / "preset-link-stage"
        spec.package.stage = DevelopStage(
            f"spack preset {spec.name}", source_path, fake_link_to_build_stage
        )

        setup_pkg = spack.build_environment.setup_package(spec.package, args.dirty)

        preset_names = {
            "name": preset_name,
            "displayName": spec_format_string(spec, args.with_display_name, user_spec=user_spec),
        }
        if args.with_description is not None:
            preset_names["description"] = spec_format_string(
                spec, args.with_description, user_spec=user_spec
            )

        configure_preset = preset_names.copy()
        configure_preset.update(
            {"cacheVariables": {}, "cmakeExecutable": spec["cmake"].prefix.bin.cmake}
        )
        if hasattr(spec.package, "generator"):
            configure_preset["generator"] = spec.package.builder.generator
        elif "ninja" in spec:
            configure_preset["generator"] = "Ninja"

        def join(sep, it):
            """Join non-empty elements."""
            return sep.join(filter(None, it))

        languages_vars = [
            ("CC", "CFLAGS", "C"),
            ("CXX", "CXXFLAGS", "CXX"),
            ("FC", "FFLAGS", "Fortran"),
        ]
        cmake_linker_flags_vars = list(
            "CMAKE_{}_LINKER_FLAGS".format(t) for t in ["EXE", "MODULE", "SHARED"]
        )

        #
        # Then, adds package's cmake -D
        #
        exclude_cmake_vars = [
            "CMAKE_VERBOSE_MAKEFILE",
            "CMAKE_INSTALL_PREFIX",
            "CMAKE_INSTALL_RPATH_USE_LINK_PATH",
            # 'CMAKE_BUILD_TYPE',
        ]
        save_for_later = {"CMAKE_INSTALL_RPATH": None, "CMAKE_BUILD_RPATH": None}
        save_for_later.update({k: None for k in cmake_linker_flags_vars})
        save_for_later.update(
            {"CMAKE_{}_FLAGS".format(cmakelang): None for _, _, cmakelang in languages_vars}
        )

        builder = spack.builder.create(spec.package)
        cmake_args = []
        if hasattr(builder, "std_cmake_args"):
            cmake_args += builder.std_cmake_args

        if hasattr(builder, "cmake_args"):
            cmake_args += builder.cmake_args()

        for arg in cmake_args:
            if arg in ["-G", "Unix Makefiles", "Ninja"]:
                continue
            k, t, v = parse_cmake_define(arg)
            if not k:
                tty.warn("Unrecognized cmake argument {!r}".format(arg))
                continue
            t = t or "STRING"
            v = v or ""
            if k in exclude_cmake_vars:
                continue
            if k in save_for_later:
                save_for_later[k] = v
                continue
            configure_preset["cacheVariables"][k] = {"type": t, "value": v}

        #
        # Add env variables.
        #
        configure_preset["environment"] = {}
        env_modifications = setup_pkg.group_by_name()
        for _, actions in sorted(env_modifications.items()):
            for modifier in actions:
                if (
                    modifier.name in [env_var for lang in languages_vars for env_var in lang]
                    or modifier.name == "F77"
                    or modifier.name == "LDCXXSHARED"
                    or modifier.name == "LDSHARED"
                    or modifier.name.startswith("SPACK_")
                    or hasattr(modifier, "value")
                    and modifier.value.startswith(os.path.join(spack_root, "lib", "spack", "env"))
                ):
                    # skipping all SPACK_ and language compiler related stuff,
                    pass  # see below for compilers
                elif isinstance(modifier, spack.util.environment.UnsetEnv):
                    pass
                elif isinstance(modifier, spack.util.environment.SetEnv) or isinstance(
                    modifier, spack.util.environment.SetPath
                ):
                    configure_preset["environment"][modifier.name] = modifier.value
                elif isinstance(modifier, spack.util.environment.PrependPath):
                    configure_preset["environment"][modifier.name] = (
                        modifier.value
                        if modifier.name not in configure_preset["environment"]
                        else modifier.value + ":" + configure_preset["environment"][modifier.name]
                    )
                elif isinstance(modifier, spack.util.environment.AppendPath):
                    configure_preset["environment"][modifier.name] = (
                        modifier.value
                        if modifier.name not in configure_preset["environment"]
                        else configure_preset["environment"][modifier.name] + ":" + modifier.value
                    )
                else:
                    tty.warn(
                        type(modifier).__name__ + ": unmanaged environment "
                        "modifier for " + modifier.name
                    )

        # no unixian can live without /usr/bin
        if "PATH" in configure_preset["environment"]:
            configure_preset["environment"]["PATH"] = (
                configure_preset["environment"]["PATH"] + ":$penv{PATH}"
            )
        # keep track of SPACK_ROOT in preset environment
        if "SPACK_ROOT" in os.environ:
            configure_preset["environment"]["SPACK_ROOT"] = os.getenv("SPACK_ROOT")
        #
        # Finally, prepend spack compiler wrapper flags
        #
        target_flags = os.getenv("SPACK_TARGET_ARGS", "")
        ldlibs = os.getenv("SPACK_LDLIBS", "")
        # /!\ CPP == C Pre Processor
        cppflags = os.getenv("SPACK_CPPFLAGS", "")

        for envlang, envflags, cmakelang in languages_vars:
            k = "CMAKE_{}_COMPILER".format(cmakelang)
            # TODO check for k for not overridding
            configure_preset["cacheVariables"][k] = {
                "type": "STRING",
                "value": os.getenv("SPACK_{}".format(envlang)),
            }

            k = "CMAKE_{}_FLAGS".format(cmakelang)
            flags = [
                os.getenv(envflags, ""),
                target_flags,
                cppflags,
                os.getenv("SPACK_{}".format(envflags), ""),
                save_for_later[k] or "",
            ]
            configure_preset["cacheVariables"][k] = {"type": "STRING", "value": join(" ", flags)}

            k = "CMAKE_{}_STANDARD_LIBRARIES".format(cmakelang)
            configure_preset["cacheVariables"][k] = {"type": "STRING", "value": ldlibs}

        ldflags = [os.getenv("LDFLAGS", ""), os.getenv("SPACK_LDFLAGS", "")]

        spack_new_dtags_flag_to_add = (
            os.getenv("SPACK_LINKER_ARG", "") + os.getenv("SPACK_DTAGS_TO_ADD", "")
            if "SPACK_DTAGS_TO_ADD" in os.environ
            else ""
        )

        for k in cmake_linker_flags_vars:

            configure_preset["cacheVariables"][k] = {
                "type": "STRING",
                "value": join(
                    " ", ldflags + [spack_new_dtags_flag_to_add] + [save_for_later[k] or ""]
                ),
            }

        rpaths = []
        rpaths.extend(os.getenv("SPACK_COMPILER_EXTRA_RPATHS", "").replace(":", ";").split(";"))
        rpaths.extend(os.getenv("SPACK_COMPILER_IMPLICIT_RPATHS", "").replace(":", ";").split(";"))
        for k in ["CMAKE_BUILD_RPATH", "CMAKE_INSTALL_RPATH"]:
            configure_preset["cacheVariables"][k] = {
                "type": "STRING",
                "value": join(
                    ";", (save_for_later[k] or "").replace(":", ";").split(";") + rpaths
                ),
            }

        if args.build_dir:
            configure_preset["binaryDir"] = spec_format_string(
                spec, args.build_dir, user_spec=user_spec, format_path=True
            )

        if args.hidden:
            configure_preset["hidden"] = True

        #
        # Add user -D
        #
        for cm_name, cm_type, cm_value in user_cmake_args:
            cm_type = cm_type or "UNINITIALIZED"
            cm_value = cm_value or ""

            existing = configure_preset["cacheVariables"].get(cm_name, None)
            if existing is not None:
                if existing["type"] != cm_type or existing["value"] != cm_value:
                    tty.warn(
                        f"Overriding {cm_name} from {existing['value']}:{existing['type']}"
                        f" to {cm_value}:{cm_type}"
                    )

            configure_preset["cacheVariables"][cm_name] = {"type": cm_type, "value": cm_value}

        presets["configurePresets"].append(configure_preset)

        if not args.no_build:  # that is build ;x
            # yes generate buildPresets key
            build_preset = preset_names.copy()
            build_preset.update({"configurePreset": preset_name})
            presets["buildPresets"].append(build_preset)

        if not args.no_test:
            test_preset = preset_names.copy()
            test_preset.update({"configurePreset": preset_name})
            presets["testPresets"].append(test_preset)

    with open(args.output, "w") as fout:
        json.dump(presets, fout, indent=2)

    tty.msg(f"Written in {args.output!r}.")
